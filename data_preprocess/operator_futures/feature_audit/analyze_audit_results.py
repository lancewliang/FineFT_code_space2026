"""Comprehensive analysis and insight extraction for multi-horizon feature audit results.

Reads the raw artifacts generated by the independent feature audit module, evaluates:
1. Feature horizon dynamics & decay trajectories (fast decay vs slow emerging).
2. Cross-contract sign consistency and sample coverage attrition.
3. Rolling time-strata stability (temporal IR, worst-case window IC, sign flip rate).
4. Dual-target profiling (directional return vs absolute volatility magnitude).
5. Spurious feature detection (unnormalized price levels).

Generates structured CSV deliverables and a self-contained Markdown executive summary.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple
import numpy as np
import pandas as pd


def parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="analyze_audit_results",
        description="Extract actionable insights and rankings from multi-horizon feature audit artifacts.",
    )
    parser.add_argument(
        "--audit-dir",
        type=str,
        default="analysis_result/DiHFT/feature_horizon_audit/fu/10min",
        help="Directory containing audit output artifacts (default: analysis_result/DiHFT/feature_horizon_audit/fu/10min)",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory to save analysis insights (default: <audit-dir>/insights)",
    )
    parser.add_argument(
        "--top-k",
        type=int,
        default=15,
        help="Number of top features to report in each category (default: 15)",
    )
    parser.add_argument(
        "--min-sign-consistency",
        type=float,
        default=0.80,
        help="Minimum cross-contract sign consistency filter (default: 0.80)",
    )
    parser.add_argument(
        "--min-coverage",
        type=float,
        default=0.50,
        help="Minimum sample coverage ratio filter (default: 0.50)",
    )
    return parser.parse_args(argv)


def load_artifacts(audit_dir: Path) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, Optional[dict]]:
    """Loads and validates required audit CSV and JSON artifacts."""
    required_files = [
        "feature_metrics.csv",
        "window_strata_metrics.csv",
        "feature_horizon_corr_matrix.csv",
        "feature_horizon_coverage_matrix.csv",
        "invalid_reasons_summary.csv",
    ]
    for filename in required_files:
        file_path = audit_dir / filename
        if not file_path.is_file():
            raise FileNotFoundError(f"Required artifact missing: {file_path}")

    fm = pd.read_csv(audit_dir / "feature_metrics.csv")
    wsm = pd.read_csv(audit_dir / "window_strata_metrics.csv")
    wsm["spearman_corr"] = pd.to_numeric(wsm["spearman_corr"], errors="coerce")
    corr_mat = pd.read_csv(audit_dir / "feature_horizon_corr_matrix.csv")
    cov_mat = pd.read_csv(audit_dir / "feature_horizon_coverage_matrix.csv")
    invalid_df = pd.read_csv(audit_dir / "invalid_reasons_summary.csv")

    manifest = None
    manifest_path = audit_dir / "audit_run_manifest.json"
    if manifest_path.is_file():
        with open(manifest_path, "r", encoding="utf-8") as f:
            manifest = json.load(f)

    return fm, wsm, corr_mat, cov_mat, invalid_df, manifest


def compute_window_stability(wsm: pd.DataFrame) -> pd.DataFrame:
    """Computes contract-equal rolling window stability metrics excluding historical reference period."""
    # Filter to valid evaluation windows (train_w01 to train_w05)
    eval_w = wsm[~wsm["is_historical_reference"]].copy()

    # Step 1: Contract-equal average per (feature, horizon, target_kind, window_id)
    win_contract_eq = (
        eval_w.groupby(["feature", "horizon", "target_kind", "window_id"])["spearman_corr"]
        .mean()
        .reset_index()
    )

    # Step 2: Aggregate across rolling evaluation windows
    def safe_sign_ratio(series: pd.Series) -> float:
        clean = series.dropna()
        if len(clean) == 0:
            return 0.0
        m = clean.mean()
        if abs(m) < 1e-9:
            return 0.5
        return float((np.sign(clean) == np.sign(m)).mean())

    def calc_temporal_ir(series: pd.Series) -> float:
        clean = series.dropna()
        if len(clean) < 2:
            return 0.0
        std = clean.std()
        if std < 1e-8:
            return 0.0
        return float(clean.mean() / std)

    grouped = win_contract_eq.groupby(["feature", "horizon", "target_kind"])["spearman_corr"]
    stats = grouped.agg(
        win_mean="mean",
        win_std="std",
        win_min="min",
        win_max="max",
        win_count="count",
    ).reset_index()

    sign_ratios = grouped.apply(safe_sign_ratio).reset_index(name="win_sign_consistency")
    ir_ratios = grouped.apply(calc_temporal_ir).reset_index(name="win_temporal_ir")

    merged = stats.merge(sign_ratios, on=["feature", "horizon", "target_kind"])
    merged = merged.merge(ir_ratios, on=["feature", "horizon", "target_kind"])
    return merged


def classify_feature_dynamics(corr_mat: pd.DataFrame, cov_mat: pd.DataFrame) -> pd.DataFrame:
    """Categorizes features by their correlation trajectory across short vs long horizons."""
    corr = corr_mat.set_index("feature")
    cov = cov_mat.set_index("feature")

    horizons = ["1h", "2h", "4h", "today", "next_td", "next_5td", "next_15td"]
    available_horizons = [h for h in horizons if h in corr.columns]

    records = []
    for feat in corr.index:
        c_1h = corr.loc[feat, "1h"] if "1h" in corr.columns else np.nan
        c_4h = corr.loc[feat, "4h"] if "4h" in corr.columns else np.nan
        c_today = corr.loc[feat, "today"] if "today" in corr.columns else np.nan
        c_15td = corr.loc[feat, "next_15td"] if "next_15td" in corr.columns else np.nan

        cov_1h = cov.loc[feat, "1h"] if "1h" in cov.columns else np.nan
        cov_15td = cov.loc[feat, "next_15td"] if "next_15td" in cov.columns else np.nan

        abs_1h = abs(c_1h) if pd.notna(c_1h) else 0.0
        abs_15td = abs(c_15td) if pd.notna(c_15td) else 0.0

        # Classification heuristics
        if abs_1h >= 0.15 and abs_1h > 2.0 * abs_15td:
            category = "FAST_DECAY_MICROSTRUCTURE"
            description = "High short-term correlation fading rapidly at daily/multi-day horizons"
        elif abs_15td >= 0.18 and abs_15td > 1.8 * abs_1h:
            category = "SLOW_EMERGING_TREND"
            description = "Weak short-term signal growing into strong long-horizon multi-day trend"
        elif abs_1h >= 0.10 and abs_15td >= 0.10 and (np.sign(c_1h) == np.sign(c_15td)):
            category = "ALL_HORIZON_PERSISTENT"
            description = "Persistent directional correlation maintained across all time horizons"
        elif abs_1h < 0.05 and abs_15td < 0.05:
            category = "NEGLIGIBLE_SIGNAL"
            description = "Low directional correlation across both short and long horizons"
        else:
            category = "INTERMEDIATE_MIXED"
            description = "Mixed horizon profile or non-monotonic trajectory"

        records.append({
            "feature": feat,
            "category": category,
            "description": description,
            "ic_1h": c_1h,
            "ic_4h": c_4h,
            "ic_today": c_today,
            "ic_next_15td": c_15td,
            "cov_1h": cov_1h,
            "cov_next_15td": cov_15td,
        })

    return pd.DataFrame(records)


def extract_top_rankings(
    fm: pd.DataFrame,
    win_stats: pd.DataFrame,
    min_sign_consistency: float,
    min_coverage: float,
    top_k: int,
) -> Dict[str, pd.DataFrame]:
    """Extracts top features for short, long, and volatility horizons with multi-layer filtering."""
    merged = fm.merge(win_stats, on=["feature", "horizon", "target_kind"], how="left")

    # Exclude non-stationary raw price level indicators that are spurious artifacts
    spurious_keywords = ["ask1_price", "bid1_price", "index_price", "UpperLimitPrice", "LowerLimitPrice"]
    non_spurious_mask = ~merged["feature"].isin(spurious_keywords)

    base_filter = (
        non_spurious_mask
        & (merged["sign_consistency"] >= min_sign_consistency)
        & (merged["coverage_ratio"] >= min_coverage)
    )

    # 1. Top Short-Horizon Directional Features (1h return)
    short_df = (
        merged[base_filter & (merged["horizon"] == "1h") & (merged["target_kind"] == "return")]
        .sort_values(by="spearman_corr", ascending=False)
        .head(top_k)
    )

    # 2. Top Long-Horizon Directional Features (next_15td return)
    long_df = (
        merged[base_filter & (merged["horizon"] == "next_15td") & (merged["target_kind"] == "return")]
        .sort_values(by="spearman_corr", ascending=False)
        .head(top_k)
    )

    # 3. Top Volatility/Magnitude Features (1h abs_return)
    vol_1h_df = (
        merged[base_filter & (merged["horizon"] == "1h") & (merged["target_kind"] == "abs_return")]
        .sort_values(by="spearman_corr", ascending=False)
        .head(top_k)
    )

    # 4. Top Volatility/Magnitude Features (next_15td abs_return)
    vol_15td_df = (
        merged[base_filter & (merged["horizon"] == "next_15td") & (merged["target_kind"] == "abs_return")]
        .sort_values(by="spearman_corr", ascending=False)
        .head(top_k)
    )

    return {
        "short_1h_return": short_df,
        "long_15td_return": long_df,
        "vol_1h_abs": vol_1h_df,
        "vol_15td_abs": vol_15td_df,
    }


def generate_executive_summary_md(
    manifest: Optional[dict],
    invalid_df: pd.DataFrame,
    cov_mat: pd.DataFrame,
    dynamics_df: pd.DataFrame,
    rankings: Dict[str, pd.DataFrame],
    top_k: int,
) -> str:
    """Renders comprehensive Markdown executive summary report."""
    symbol = manifest.get("symbol", "fu") if manifest else "fu"
    freq = manifest.get("frequency", "10min") if manifest else "10min"
    total_features = len(dynamics_df)

    category_counts = dynamics_df["category"].value_counts().to_dict()

    cov_summary = []
    horizons = ["1h", "2h", "4h", "today", "next_td", "next_5td", "next_15td"]
    for h in horizons:
        if h in cov_mat.columns:
            cov_summary.append(f"| `{h}` | {cov_mat[h].mean():.2%} | {cov_mat[h].min():.2%} |")

    # Format tables for rankings
    def df_to_markdown_table(df: pd.DataFrame, cols: List[str], headers: List[str]) -> str:
        if df.empty:
            return "_No features satisfied the filtering criteria._\n"
        sub = df[cols].copy()
        # Round numerical columns
        for c in sub.columns:
            if sub[c].dtype == float:
                sub[c] = sub[c].apply(lambda x: f"{x:.4f}" if pd.notna(x) else "-")
        header_line = "| " + " | ".join(headers) + " |"
        sep_line = "| " + " | ".join(["---"] * len(headers)) + " |"
        rows = ["| " + " | ".join(str(val) for val in row) + " |" for row in sub.values]
        return "\n".join([header_line, sep_line] + rows) + "\n"

    cols_return = ["feature", "spearman_corr", "sign_consistency", "win_mean", "win_temporal_ir", "win_sign_consistency", "coverage_ratio"]
    headers_return = ["Feature", "Spearman IC", "Contract Consistency", "Window Mean IC", "Temporal IR", "Window Consistency", "Coverage"]

    cols_abs = ["feature", "spearman_corr", "sign_consistency", "win_mean", "win_temporal_ir", "coverage_ratio"]
    headers_abs = ["Feature", "Abs Return IC", "Contract Consistency", "Window Mean IC", "Temporal IR", "Coverage"]

    table_short = df_to_markdown_table(rankings["short_1h_return"], cols_return, headers_return)
    table_long = df_to_markdown_table(rankings["long_15td_return"], cols_return, headers_return)
    table_vol_1h = df_to_markdown_table(rankings["vol_1h_abs"], cols_abs, headers_abs)
    table_vol_15td = df_to_markdown_table(rankings["vol_15td_abs"], cols_abs, headers_abs)

    md = f"""# Multi-Horizon Feature Audit Executive Summary: {symbol.upper()} ({freq})

## 1. Overview & Methodological Context
- **Target Symbol**: `{symbol}`
- **Sampling Frequency**: `{freq}`
- **Evaluated Features Count**: `{total_features}`
- **Research Protocol**: `multi_horizon_audit.research.v1` (ADR-0053 / ADR-0054)
- **Evaluation Windows**: 6-month historical warm-up reference + 5 rolling 3-month evaluation windows across 14 contracts.

> **Methodological Disclaimer**:
> Audit results represent retrospective characterization based on standard Spearman rank IC and rolling-window consistency. 
> They do not constitute an automated promotion/deletion gate nor direct PnL guarantees. All confidence intervals strictly respect the 20-effective-block requirement of Protocol Q14.

---

## 2. Sample Coverage & Invalid Reason Distribution
As prediction horizons extend from intraday (1h) to multi-week (15TD), label maturity and boundary purge mechanisms lead to natural sample attrition:

| Horizon | Mean Coverage | Min Coverage |
|---|---|---|
{chr(10).join(cov_summary)}

- **Top Invalidation Drivers (15TD)**: `UNMATURED_AT_WINDOW_BOUNDARY` (strictly prevents window-edge lookahead bias) and `STALE_PRICE` (lack of continuous trading in far-month contracts).

---

## 3. Horizon Dynamics Classification
Features categorized by correlation trajectory between short horizon (1h) and long horizon (15TD):

- **Fast Decay Microstructure (`FAST_DECAY_MICROSTRUCTURE`)**: {category_counts.get('FAST_DECAY_MICROSTRUCTURE', 0)} features
  - High initial correlation at 1h, rapidly vanishing as horizon approaches daily/weekly close.
- **Slow Emerging Trend (`SLOW_EMERGING_TREND`)**: {category_counts.get('SLOW_EMERGING_TREND', 0)} features
  - **Key Stage 6.5 Finding**: Features previously discarded under legacy 6-bar (~60min) gates that exhibit strong predictive power for 5TD~15TD trends.
- **All-Horizon Persistent (`ALL_HORIZON_PERSISTENT`)**: {category_counts.get('ALL_HORIZON_PERSISTENT', 0)} features
  - Steady directional alignment sustained across both intraday and multi-day horizons.
- **Other / Negligible Signal**: {category_counts.get('NEGLIGIBLE_SIGNAL', 0) + category_counts.get('INTERMEDIATE_MIXED', 0)} features

---

## 4. Top Short-Horizon Directional Features (1h Return, Top {top_k})
Filtered by cross-contract sign consistency $\ge 80\%$ and sample coverage $\ge 50\%$:

{table_short}

---

## 5. Top Long-Horizon Directional Features (next_15td Return, Top {top_k})
Filtered by cross-contract sign consistency $\ge 80\%$ and sample coverage $\ge 50\%$:

{table_long}

---

## 6. Top Volatility / Magnitude Signals (abs_return)
Features predicting absolute return amplitude (market volatility & regime states):

### Short Horizon (1h abs_return)
{table_vol_1h}

### Long Horizon (next_15td abs_return)
{table_vol_15td}

---

## 7. Actionable Architectural Takeaways
1. **Multi-Scale Gating**: Short-horizon agents (e.g., execution, micro-trend) should be conditioned on `FAST_DECAY` order book features (e.g., `ask1_price_trend_2`), while long-horizon policy agents should consume `SLOW_EMERGING` trend features (`min_192_origin`, `roc_192_origin`).
2. **State Augmentation**: Features with high `abs_return` correlation (e.g., `night_session`, `cm_m1_m2_open_interest_share_m2`, `pivot_s1_192_origin`) are ideal inputs for the RL environment's risk and volatility state.
3. **Spurious Filter**: Raw, unnormalized nominal price levels (`ask1_price`, `index_price`) must remain excluded from trading state vectors to avoid non-stationary overfitting.
"""
    return md


def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    audit_dir = Path(args.audit_dir)
    output_dir = Path(args.output_dir) if args.output_dir else audit_dir / "insights"
    output_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 80)
    print(f"🔍 Analyzing Multi-Horizon Feature Audit Results")
    print(f"  Audit Directory:  {audit_dir}")
    print(f"  Output Directory: {output_dir}")
    print("=" * 80)

    # 1. Load data
    try:
        fm, wsm, corr_mat, cov_mat, invalid_df, manifest = load_artifacts(audit_dir)
        print(f"✔ Successfully loaded artifacts ({len(corr_mat)} features, {len(fm)} metrics)")
    except FileNotFoundError as e:
        print(f"❌ 错误: {e}")
        print("  提示: 请先运行特征审计任务生成原始评估产物，例如:")
        print("        ./data_preprocess/script_preprocess/future_upgraded/commodity/run_audit_fu_10min.sh")
        return 1

    # 2. Window strata stability
    print("▶ Evaluating rolling window stability and temporal IR...")
    win_stats = compute_window_stability(wsm)

    # 3. Horizon dynamics classification
    print("▶ Classifying feature horizon dynamics (fast decay vs slow emerging)...")
    dynamics_df = classify_feature_dynamics(corr_mat, cov_mat)

    # 4. Top rankings
    print("▶ Extracting robust top features across short, long, and volatility horizons...")
    rankings = extract_top_rankings(
        fm=fm,
        win_stats=win_stats,
        min_sign_consistency=args.min_sign_consistency,
        min_coverage=args.min_coverage,
        top_k=args.top_k,
    )

    # 5. Persist output files
    print("▶ Saving insight deliverables...")
    dynamics_df.to_csv(output_dir / "feature_dynamics_classification.csv", index=False)
    rankings["short_1h_return"].to_csv(output_dir / "top_short_horizon_features.csv", index=False)
    rankings["long_15td_return"].to_csv(output_dir / "top_long_horizon_features.csv", index=False)
    rankings["vol_1h_abs"].to_csv(output_dir / "top_volatility_1h_features.csv", index=False)
    rankings["vol_15td_abs"].to_csv(output_dir / "top_volatility_15td_features.csv", index=False)

    summary_md = generate_executive_summary_md(
        manifest=manifest,
        invalid_df=invalid_df,
        cov_mat=cov_mat,
        dynamics_df=dynamics_df,
        rankings=rankings,
        top_k=args.top_k,
    )
    with open(output_dir / "executive_summary.md", "w", encoding="utf-8") as f:
        f.write(summary_md)

    print("✔ All insight deliverables written successfully.")
    print("-" * 80)
    print("📊 Executive Summary Highlights:")
    print(f"  - Fast Decay (Microstructure) Features: {len(dynamics_df[dynamics_df['category'] == 'FAST_DECAY_MICROSTRUCTURE'])}")
    print(f"  - Slow Emerging (Long-Horizon) Features: {len(dynamics_df[dynamics_df['category'] == 'SLOW_EMERGING_TREND'])}")
    print(f"  - All-Horizon Persistent Features:       {len(dynamics_df[dynamics_df['category'] == 'ALL_HORIZON_PERSISTENT'])}")
    print("-" * 80)
    print("🏆 Top 3 Short-Horizon Features (1h Return):")
    for _, row in rankings["short_1h_return"].head(3).iterrows():
        print(f"  • {row['feature']:<30} IC: {row['spearman_corr']:+.4f} | Consistency: {row['sign_consistency']:.1%} | Temporal IR: {row['win_temporal_ir']:+.2f}")

    print("\n🏆 Top 3 Long-Horizon Features (next_15td Return):")
    for _, row in rankings["long_15td_return"].head(3).iterrows():
        print(f"  • {row['feature']:<30} IC: {row['spearman_corr']:+.4f} | Consistency: {row['sign_consistency']:.1%} | Temporal IR: {row['win_temporal_ir']:+.2f}")

    print("\n🏆 Top 3 Volatility Features (next_15td Abs Return):")
    for _, row in rankings["vol_15td_abs"].head(3).iterrows():
        print(f"  • {row['feature']:<30} Abs IC: {row['spearman_corr']:+.4f} | Consistency: {row['sign_consistency']:.1%} | Temporal IR: {row['win_temporal_ir']:+.2f}")

    print("=" * 80)
    print(f"🎉 Complete summary report available at: {output_dir / 'executive_summary.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
