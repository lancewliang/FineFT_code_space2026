"""Comprehensive analysis and insight extraction for multi-horizon feature audit results.

Reads the raw artifacts generated by the independent feature audit module, evaluates:
1. Feature horizon dynamics & decay trajectories across scales (micro, short, medium, long).
2. Cross-contract sign consistency and sample coverage attrition.
3. Rolling time-strata stability (temporal IR, worst-case window IC, sign flip rate).
4. Dual-target profiling (directional return vs absolute volatility magnitude).
5. Spurious feature detection (unnormalized price levels).

Generates structured CSV deliverables for each evaluated horizon and a self-contained Markdown executive summary.
"""

