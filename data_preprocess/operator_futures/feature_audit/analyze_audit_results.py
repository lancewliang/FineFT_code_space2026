def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    audit_dir = Path(args.audit_dir)
    output_dir = Path(args.output_dir) if args.output_dir else audit_dir / "insights"
    output_dir.mkdir(parents=True, exist_ok=True)

    target_horizons = [normalize_horizon(h) for h in args.horizons.split(",") if h.strip()]
    if not target_horizons or any(h not in HORIZON_METADATA for h in target_horizons):
        raise ValueError(f"Unsupported or empty horizon list: {target_horizons}")
    target_horizons = list(dict.fromkeys(target_horizons))
    if args.top_k < 1 or not 0 <= args.min_sign_consistency <= 1 or not 0 <= args.min_coverage <= 1:
        raise ValueError("top-k must be positive and display thresholds must be between 0 and 1")
    if args.config and args.legacy_selection_manifest:
        raise ValueError("Provide either --config or --legacy-selection-manifest, not both")

    print("=" * 80)
    print(f"🔍 Analyzing Multi-Horizon Feature Audit Results")
    print(f"  Audit Directory:  {audit_dir}")
    print(f"  Output Directory: {output_dir}")
    print(f"  Target Horizons:  {', '.join(target_horizons)}")
    print("=" * 80)

    # 1. Load data
    try:
        fm, wsm, corr_mat, cov_mat, invalid_df, manifest = load_artifacts(audit_dir)
        print(f"✔ Successfully loaded artifacts ({len(corr_mat)} features, {len(fm)} metrics)")
    except FileNotFoundError as e:
        print(f"❌ 错误: {e}")
        print("  提示: 请先运行特征审计任务生成原始评估产物，例如:")
        print("        ./data_preprocess/script_preprocess/future_upgraded/commodity/run_audit_fu_10min.sh")
        return 1

    override = args.legacy_selection_manifest
    if args.config:
        config = AuditConfig.load(args.config)
        if manifest and (config.symbol != manifest.get("symbol") or config.frequency != manifest.get("frequency")):
            raise ValueError("Annotation config symbol/frequency does not match the audit")
        override = Path(config.legacy_selection_manifest) if config.legacy_selection_manifest else None
    annotations, provenance = selection_annotations(
        audit_dir, fm["feature"].drop_duplicates().tolist(), manifest, override
    )
    fm = fm.drop(columns=[c for c in annotations.columns if c != "feature" and c in fm])
    fm = fm.merge(annotations, on="feature", how="left", validate="many_to_one")
    fm = annotate_ci_evidence(fm)
    evidence = build_evidence_summary(fm, wsm, audit_dir, provenance)
    evidence["display_parameters"] = {
        "horizons": target_horizons, "top_k": args.top_k,
        "min_sign_consistency": args.min_sign_consistency, "min_coverage": args.min_coverage,
        "ranking": "absolute_ic_with_signed_values",
    }
    evidence["source_artifacts"] = {
        path.name: hashlib.sha256(path.read_bytes()).hexdigest()
        for path in [audit_dir / name for name in (
            "feature_metrics.csv", "window_strata_metrics.csv", "feature_horizon_corr_matrix.csv",
            "feature_horizon_coverage_matrix.csv", "invalid_reasons_summary.csv", "audit_run_manifest.json",
            "ci_diagnostics.csv", "matched_horizon_comparisons.csv",
        )] if path.is_file()
    }

    # 2. Window strata stability
    print("▶ Evaluating rolling window stability and temporal IR...")
    win_stats = compute_window_stability(wsm)

    # 3. Horizon dynamics classification
    print("▶ Classifying feature horizon dynamics (fast decay vs slow emerging)...")
    dynamics_df = classify_feature_dynamics(corr_mat, cov_mat)
    dynamics_df = dynamics_df.merge(annotations, on="feature", how="left", validate="one_to_one")

    # 4. Top rankings
    print(f"▶ Preparing exploratory display lists across {len(target_horizons)} horizons...")
    rankings = extract_top_rankings(
        fm=fm,
        win_stats=win_stats,
        target_horizons=target_horizons,
        min_sign_consistency=args.min_sign_consistency,
        min_coverage=args.min_coverage,
        top_k=args.top_k,
    )

    # 5. Persist output files
    print("▶ Saving insight deliverables...")
    dynamics_df.to_csv(output_dir / "feature_dynamics_classification.csv", index=False)
    annotations.to_csv(output_dir / "legacy_selection_comparison.csv", index=False)
    fm.to_csv(output_dir / "feature_evidence.csv", index=False)
    fm.groupby(["horizon", "target_kind", "ci_status", "ci_status_2x"]).size().reset_index(
        name="metric_rows"
    ).to_csv(output_dir / "ci_evidence_summary.csv", index=False)
    dynamics_df.groupby(["category", "selection_status", "drop_reason_status"]).size().reset_index(
        name="feature_count"
    ).to_csv(output_dir / "selection_dynamics_summary.csv", index=False)
    (output_dir / "analysis_manifest.json").write_text(
        json.dumps(evidence, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    for h in target_horizons:
        ret_key = f"return_{h}"
        vol_key = f"vol_{h}"
        rankings[ret_key].to_csv(output_dir / f"top_return_{h}_features.csv", index=False)
        rankings[vol_key].to_csv(output_dir / f"top_volatility_{h}_features.csv", index=False)

    # Legacy output file aliases for backward compatibility
    if "return_1h" in rankings:
        rankings["return_1h"].to_csv(output_dir / "top_short_horizon_features.csv", index=False)
    if "return_next_15td" in rankings:
        rankings["return_next_15td"].to_csv(output_dir / "top_long_horizon_features.csv", index=False)
    if "vol_next_15td" in rankings:
        rankings["vol_next_15td"].to_csv(output_dir / "top_volatility_15td_features.csv", index=False)

    summary_md = generate_executive_summary_md(
        manifest=manifest,
        invalid_df=invalid_df,
        cov_mat=cov_mat,
        dynamics_df=dynamics_df,
        rankings=rankings,
        target_horizons=target_horizons,
        top_k=args.top_k,
        evidence=evidence,
        min_sign_consistency=args.min_sign_consistency,
        min_coverage=args.min_coverage,
        metrics=fm,
        audit_dir=audit_dir,
        output_dir=output_dir,
    )
    with open(output_dir / "executive_summary.md", "w", encoding="utf-8") as f:
        f.write(summary_md)

    print("✔ All insight deliverables written successfully.")
    print("-" * 80)
    print("📊 Executive Summary Highlights:")
    print(f"  - Fast Decay (Microstructure) Features: {len(dynamics_df[dynamics_df['category'] == 'FAST_DECAY_MICROSTRUCTURE'])}")
    print(f"  - Slow Emerging (Long-Horizon) Features: {len(dynamics_df[dynamics_df['category'] == 'SLOW_EMERGING_TREND'])}")
    print(f"  - Endpoint Sign Aligned Features:       {len(dynamics_df[dynamics_df['category'] == 'ENDPOINT_SIGN_ALIGNED'])}")
    print("-" * 80)

    for h in target_horizons:
        meta = HORIZON_METADATA.get(h, {"name": h})
        ret_df = rankings.get(f"return_{h}", pd.DataFrame())
        print(f"\n🏆 Top 3 Features: {meta['name']} (Directional Return):")
        if ret_df.empty:
            print("  (无符合阈值特征)")
        else:
            for _, row in ret_df.head(3).iterrows():
                print(f"  • {row['feature']:<30} IC: {row['spearman_corr']:+.4f} | Consistency: {row['sign_consistency']:.1%} | Temporal IR: {row['win_temporal_ir']:+.2f}")

    for h in target_horizons:
        meta = HORIZON_METADATA.get(h, {"name": h})
        vol_df = rankings.get(f"vol_{h}", pd.DataFrame())
        print(f"\n⚡ Top 3 Endpoint Magnitude Associations: {meta['name']} (abs_return):")
        if vol_df.empty:
            print("  (无符合阈值特征)")
        else:
            for _, row in vol_df.head(3).iterrows():
                print(f"  • {row['feature']:<30} Abs IC: {row['spearman_corr']:+.4f} | Consistency: {row['sign_consistency']:.1%} | Temporal IR: {row['win_temporal_ir']:+.2f}")

    print("=" * 80)
    print(f"🎉 Complete summary report available at: {output_dir / 'executive_summary.md'}")
    return 0


