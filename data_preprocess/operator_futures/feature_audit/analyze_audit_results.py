def load_artifacts(audit_dir: Path) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, Optional[dict]]:
    """Loads and validates required audit CSV and JSON artifacts."""
    required_files = [
        "feature_metrics.csv",
        "window_strata_metrics.csv",
        "feature_horizon_corr_matrix.csv",
        "feature_horizon_coverage_matrix.csv",
        "invalid_reasons_summary.csv",
    ]
    for filename in required_files:
        file_path = audit_dir / filename
        if not file_path.is_file():
            raise FileNotFoundError(f"Required artifact missing: {file_path}")

    fm = pd.read_csv(audit_dir / "feature_metrics.csv")
    wsm = pd.read_csv(audit_dir / "window_strata_metrics.csv")
    wsm["spearman_corr"] = pd.to_numeric(wsm["spearman_corr"], errors="coerce")
    corr_mat = pd.read_csv(audit_dir / "feature_horizon_corr_matrix.csv")
    cov_mat = pd.read_csv(audit_dir / "feature_horizon_coverage_matrix.csv")
    invalid_df = pd.read_csv(audit_dir / "invalid_reasons_summary.csv")

    manifest = None
    manifest_path = audit_dir / "audit_run_manifest.json"
    if manifest_path.is_file():
        with open(manifest_path, "r", encoding="utf-8") as f:
            manifest = json.load(f)

    return fm, wsm, corr_mat, cov_mat, invalid_df, manifest


def selection_annotations(
    audit_dir: Path, features: list[str], manifest: dict | None, override: Path | None
) -> tuple[pd.DataFrame, dict]:
    """Use saved selection evidence, or an explicit retrospective manifest override."""
    sidecar = audit_dir / "legacy_selection_comparison.csv"
    recorded_source = (manifest or {}).get("legacy_selection_source", {})
    if override is not None or (not sidecar.exists() and recorded_source.get("path")):
        selection = load_legacy_selection(override or recorded_source["path"])
        if override is None and selection.sha256 != recorded_source.get("sha256"):
            raise ValueError("Selection manifest changed since audit; use an explicit override")
        annotations = pd.DataFrame(selection.comparison_rows(features))
        provenance = {
            "mode": "explicit_retrospective" if override else "audit_manifest_verified",
            "path": selection.source_path,
            "sha256": selection.sha256,
        }
    elif sidecar.exists():
        annotations = pd.read_csv(sidecar)
        provenance = {"mode": "saved_audit_annotations", "path": str(sidecar.resolve())}
        provenance["sha256"] = hashlib.sha256(sidecar.read_bytes()).hexdigest()
        if recorded_source and (
            "source_sha256" not in annotations
            or not annotations["source_sha256"].eq(recorded_source.get("sha256")).all()
        ):
            raise ValueError("Selection annotation fingerprint does not match audit manifest")
    else:
        annotations = pd.DataFrame({
            "feature": features, "legacy_stream_membership": "unassigned",
            "is_selected": pd.NA, "selected_streams": "[]", "drop_reasons": "[]",
            "drop_reason_status": "unknown",
        })
        provenance = {"mode": "unavailable"}

    required = {
        "feature", "legacy_stream_membership", "is_selected", "selected_streams",
        "drop_reasons", "drop_reason_status",
    }
    if not required.issubset(annotations.columns) or annotations["feature"].duplicated().any():
        raise ValueError("Selection annotations must contain unique features and evidence columns")
    if not set(features).issubset(set(annotations["feature"])):
        raise ValueError("Selection annotations do not cover all audited features")
    annotations = annotations[annotations["feature"].isin(features)].copy()
    annotations["is_selected"] = annotations["is_selected"].astype("boolean")
    annotations["selection_status"] = annotations["is_selected"].map(
        {True: "selected", False: "not_selected"}
    ).fillna("unknown")
    return annotations, provenance


def annotate_ci_evidence(metrics: pd.DataFrame) -> pd.DataFrame:
    """Expose available intervals without inventing reasons for historical missing CIs."""
    result = metrics.copy()
    for suffix in ("", "_2x"):
        lower = pd.to_numeric(result.get(f"ci_lower{suffix}", pd.Series(np.nan, index=result.index)))
        upper = pd.to_numeric(result.get(f"ci_upper{suffix}", pd.Series(np.nan, index=result.index)))
        valid = np.isfinite(lower) & np.isfinite(upper) & (lower <= upper)
        status_col = f"ci_status{suffix}"
        reported = result.get(status_col, pd.Series(pd.NA, index=result.index))
        result[status_col] = reported.fillna("MISSING_CI_REASON_UNRECORDED")
        result.loc[valid, status_col] = "AVAILABLE_EXPLORATORY"
        result.loc[~valid & reported.eq("OK").fillna(False), status_col] = "INVALID_CI_ARTIFACT"
    return result


def build_evidence_summary(
    metrics: pd.DataFrame, windows: pd.DataFrame, audit_dir: Path, provenance: dict
) -> dict:
    """Describe observed evidence coverage and evaluate matched comparison artifacts."""
    evaluation = windows[~windows["is_historical_reference"]]
    matched = audit_dir / "matched_horizon_comparisons.csv"
    matched_status = "NOT_AVAILABLE"
    matched_meta = {}
    if matched.is_file():
        try:
            m_df = pd.read_csv(matched)
            if len(m_df) > 0 and "ic_common_1h" in m_df.columns:
                matched_status = "COMPLETED_MATCHED_EVALUATION"
                matched_meta = {
                    "matched_samples": int(m_df["matched_samples"].iloc[0]) if "matched_samples" in m_df.columns else len(m_df),
                    "sample_retention_ratio": float(m_df["sample_retention_ratio"].iloc[0]) if "sample_retention_ratio" in m_df.columns else 0.0,
                }
            else:
                matched_status = "PRESENT_NOT_VALIDATED"
        except Exception:
            matched_status = "PRESENT_NOT_VALIDATED"

    summary = {
        "selection_source": provenance,
        "evaluation_window_count": int(evaluation["window_id"].nunique()),
        "contract_count": int(evaluation["contract"].nunique()),
        "metric_rows": len(metrics),
        "ci_status_counts": metrics["ci_status"].value_counts().to_dict(),
        "ci_status_2x_counts": metrics["ci_status_2x"].value_counts().to_dict(),
        "matched_horizon_status": matched_status,
        "matched_horizon_path": str(matched.resolve()) if matched.is_file() else None,
    }
    summary.update(matched_meta)
    return summary


def compute_window_stability(wsm: pd.DataFrame) -> pd.DataFrame:
    """Computes contract-equal rolling window stability metrics excluding historical reference period."""
    eval_w = wsm[~wsm["is_historical_reference"]].copy()

    win_contract_eq = (
        eval_w.groupby(["feature", "horizon", "target_kind", "window_id"])["spearman_corr"]
        .mean()
        .reset_index()
    )

    def safe_sign_ratio(series: pd.Series) -> float:
        clean = series.dropna()
        if len(clean) == 0:
            return 0.0
        m = clean.mean()
        if abs(m) < 1e-9:
            return 0.5
        return float((np.sign(clean) == np.sign(m)).mean())

    def calc_temporal_ir(series: pd.Series) -> float:
        clean = series.dropna()
        if len(clean) < 2:
            return 0.0
        std = clean.std()
        if std < 1e-8:
            return 0.0
        return float(clean.mean() / std)

    grouped = win_contract_eq.groupby(["feature", "horizon", "target_kind"])["spearman_corr"]
    stats = grouped.agg(
        win_mean="mean",
        win_std="std",
        win_min="min",
        win_max="max",
        win_count="count",
    ).reset_index()

    sign_ratios = grouped.apply(safe_sign_ratio).reset_index(name="win_sign_consistency")
    ir_ratios = grouped.apply(calc_temporal_ir).reset_index(name="win_temporal_ir")

    merged = stats.merge(sign_ratios, on=["feature", "horizon", "target_kind"])
    merged = merged.merge(ir_ratios, on=["feature", "horizon", "target_kind"])
    return merged


def classify_feature_dynamics(corr_mat: pd.DataFrame, cov_mat: pd.DataFrame) -> pd.DataFrame:
    """Categorizes features by their correlation trajectory across short vs long horizons."""
    corr = corr_mat.set_index("feature")
    cov = cov_mat.set_index("feature")

    horizons = ["1h", "2h", "4h", "today", "next_td", "next_5td", "next_15td"]
    available_horizons = [h for h in horizons if h in corr.columns]

    records = []
    for feat in corr.index:
        c_1h = corr.loc[feat, "1h"] if "1h" in corr.columns else np.nan
        c_15td = corr.loc[feat, "next_15td"] if "next_15td" in corr.columns else np.nan

        abs_1h = abs(c_1h) if pd.notna(c_1h) else 0.0
        abs_15td = abs(c_15td) if pd.notna(c_15td) else 0.0

        if not np.isfinite(c_1h) or not np.isfinite(c_15td):
            category = "INSUFFICIENT_HORIZON_DATA"
            description = "Missing endpoint correlation; no dynamics classification"
        elif abs_1h >= 0.15 and abs_1h > 2.0 * abs_15td:
            category = "FAST_DECAY_MICROSTRUCTURE"
            description = "High short-term correlation fading rapidly at daily/multi-day horizons"
        elif abs_15td >= 0.18 and abs_15td > 1.8 * abs_1h:
            category = "SLOW_EMERGING_TREND"
            description = "Weak short-term signal growing into strong long-horizon multi-day trend"
        elif abs_1h >= 0.10 and abs_15td >= 0.10 and (np.sign(c_1h) == np.sign(c_15td)):
            category = "ENDPOINT_SIGN_ALIGNED"
            description = "Same correlation sign at 1h and 15TD; intermediate horizons may differ"
        elif abs_1h < 0.05 and abs_15td < 0.05:
            category = "NEGLIGIBLE_SIGNAL"
            description = "Low directional correlation across both short and long horizons"
        else:
            category = "INTERMEDIATE_MIXED"
            description = "Mixed horizon profile or non-monotonic trajectory"

        record = {
            "feature": feat,
            "category": category,
            "description": description,
        }
        for h in available_horizons:
            record[f"ic_{h}"] = corr.loc[feat, h]
            if h in cov.columns:
                record[f"cov_{h}"] = cov.loc[feat, h]
        records.append(record)

    return pd.DataFrame(records)


def extract_top_rankings(
    fm: pd.DataFrame,
    win_stats: pd.DataFrame,
    target_horizons: List[str],
    min_sign_consistency: float,
    min_coverage: float,
    top_k: int,
) -> Dict[str, pd.DataFrame]:
    """Extracts top features for specified horizons and target kinds with multi-layer filtering."""
    merged = fm.merge(win_stats, on=["feature", "horizon", "target_kind"], how="left")
    merged["absolute_ic"] = merged["spearman_corr"].abs()

    spurious_keywords = ["ask1_price", "bid1_price", "index_price", "UpperLimitPrice", "LowerLimitPrice"]
    non_spurious_mask = ~merged["feature"].isin(spurious_keywords)

    base_filter = (
        non_spurious_mask
        & (merged["sign_consistency"] >= min_sign_consistency)
        & (merged["coverage_ratio"] >= min_coverage)
    )

    rankings: Dict[str, pd.DataFrame] = {}

    for horizon in target_horizons:
        ret_df = (
            merged[base_filter & (merged["horizon"] == horizon) & (merged["target_kind"] == "return")]
            .sort_values(by="absolute_ic", ascending=False)
            .head(top_k)
        )
        vol_df = (
            merged[base_filter & (merged["horizon"] == horizon) & (merged["target_kind"] == "abs_return")]
            .sort_values(by="absolute_ic", ascending=False)
            .head(top_k)
        )
        rankings[f"return_{horizon}"] = ret_df
        rankings[f"vol_{horizon}"] = vol_df

    # Backward compatibility mappings
    if "1h" in target_horizons:
        rankings["short_1h_return"] = rankings["return_1h"]
        rankings["vol_1h_abs"] = rankings["vol_1h"]
    if "next_15td" in target_horizons:
        rankings["long_15td_return"] = rankings["return_next_15td"]
        rankings["vol_15td_abs"] = rankings["vol_next_15td"]

    return rankings


